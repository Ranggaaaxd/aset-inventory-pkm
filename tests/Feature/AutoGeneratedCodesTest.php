<?php

namespace Tests\Feature;

use App\Models\Asset;
use App\Models\Supply;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Carbon;
use Tests\TestCase;

class AutoGeneratedCodesTest extends TestCase
{
    use RefreshDatabase;

    protected function tearDown(): void
    {
        Carbon::setTestNow();

        parent::tearDown();
    }

    public function test_asset_codes_are_generated_sequentially_for_the_current_year(): void
    {
        Carbon::setTestNow(Carbon::create(2026, 10, 29));

        $firstAsset = Asset::create(['name' => 'Laptop', 'condition' => 'Baik']);
        $secondAsset = Asset::create(['name' => 'Printer', 'condition' => 'Baik']);

        $this->assertSame('PKM-AST-2026-0001', $firstAsset->asset_code);
        $this->assertSame('PKM-AST-2026-0002', $secondAsset->asset_code);
    }

    public function test_supply_codes_are_generated_after_the_highest_existing_number(): void
    {
        Supply::create([
            'item_code' => 'PKM-ATK-0003',
            'name' => 'Kertas',
        ]);

        $supply = Supply::create(['name' => 'Pulpen']);

        $this->assertSame('PKM-ATK-0004', $supply->item_code);
    }

    public function test_asset_and_supply_codes_keep_explicit_values(): void
    {
        $asset = Asset::create([
            'asset_code' => 'CUSTOM-ASSET-01',
            'name' => 'Kursi',
            'condition' => 'Baik',
        ]);
        $supply = Supply::create([
            'item_code' => 'CUSTOM-SUPPLY-01',
            'name' => 'Map',
        ]);

        $this->assertSame('CUSTOM-ASSET-01', $asset->asset_code);
        $this->assertSame('CUSTOM-SUPPLY-01', $supply->item_code);
    }
}
